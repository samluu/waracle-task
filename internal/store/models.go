package store

import (
	"time"

	"github.com/google/uuid"
)

type RoomType string

const (
	RoomTypeSingle RoomType = "single"
	RoomTypeDouble RoomType = "double"
	RoomTypeDeluxe RoomType = "deluxe"
)

type Hotel struct {
	ID   int64  `db:"id"`
	Name string `db:"name"`
}

type Room struct {
	ID      int64    `db:"id"`
	HotelID int64    `db:"hotel_id"`
	Number  string   `db:"number"`
	Type    RoomType `db:"type"`
	// Capacity and HotelName come from room_types and hotels; queries join them in.
	Capacity  int    `db:"capacity"`
	HotelName string `db:"hotel_name"`
}

type Booking struct {
	Reference uuid.UUID `db:"reference"` // generated by the database
	RoomID    int64     `db:"room_id"`
	GuestName string    `db:"guest_name"`
	Guests    int       `db:"guests"`
	// CheckIn and CheckOut are dates (midnight UTC); the stay covers the nights [CheckIn, CheckOut).
	CheckIn   time.Time `db:"check_in"`
	CheckOut  time.Time `db:"check_out"`
	CreatedAt time.Time `db:"created_at"`
}

// BookingDetails is a booking with its room and hotel, as returned to API consumers.
// Queries alias the room's columns as "room.<column>" for sqlx to fill Room.
type BookingDetails struct {
	Booking
	Room Room `db:"room"`
}
